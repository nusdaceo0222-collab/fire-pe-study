const CACHE_NAME = 'fire-pe-study-v4';
const APP_SHELL = [
  '/fire-pe-study/',
  '/fire-pe-study/index.html',
  '/fire-pe-study/manifest.json',
  '/fire-pe-study/icon-192.png',
  '/fire-pe-study/icon-512.png'
];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME).then(cache => cache.addAll(APP_SHELL))
  );
  self.skipWaiting();
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys().then(keys =>
      Promise.all(keys.filter(key => key !== CACHE_NAME).map(key => caches.delete(key)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;

  if (event.request.mode === 'navigate') {
    event.respondWith(
      fetch(event.request)
        .then(response => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put('/fire-pe-study/index.html', copy));
          return response;
        })
        .catch(() => caches.match('/fire-pe-study/index.html'))
    );
    return;
  }

  event.respondWith(
    caches.match(event.request).then(cached => cached || fetch(event.request))
  );
});
